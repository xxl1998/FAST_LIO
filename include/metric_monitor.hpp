  double nowSec() const {
    return config_.clock_now_sec ? config_.clock_now_sec() : 0.0;
  }

  static std::chrono::duration<double> secondsToDuration(double seconds) {
    return std::chrono::duration<double>(std::max(0.001, seconds));
  }

  static bool isFinite(double value) { return std::isfinite(value); }

  static std::string sanitizeName(const std::string& input) {
    std::string out;
    out.reserve(input.size());
    for (char c : input) {
      const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                      (c >= '0' && c <= '9') || c == '_' || c == '-' ||
                      c == '/' || c == '.';
      out.push_back(ok ? c : '_');
    }
    return out.empty() ? "unnamed" : out;
  }

  static std::string sanitizeFileName(const std::string& input) {
    std::string out = sanitizeName(input);
    std::replace(out.begin(), out.end(), '/', '_');
    return out;
  }

  static std::string makeDateStamp(double timestamp_sec) {
    const auto tt = static_cast<std::time_t>(timestamp_sec);
    std::tm tm{};
#if defined(_WIN32)
    localtime_s(&tm, &tt);
#else
    localtime_r(&tt, &tm);
#endif
    std::ostringstream oss;
    oss << std::put_time(&tm, "%Y%m%d_%H%M%S");
    return oss.str();
  }

  static std::string formatDouble(double value) {
    if (std::isnan(value)) {
      return "nan";
    }
    if (std::isinf(value)) {
      return value > 0.0 ? "inf" : "-inf";
    }
    std::ostringstream oss;
    oss << std::fixed << std::setprecision(9) << value;
    return oss.str();
  }

  static std::string formatJsonNumber(double value) {
    if (!std::isfinite(value)) {
      return "null";
    }
    return formatDouble(value);
  }

  static std::string jsonEscape(const std::string& input) {
    std::ostringstream oss;
    for (char c : input) {
      switch (c) {
        case '"':
          oss << "\\\"";
          break;
        case '\\':
          oss << "\\\\";
          break;
        case '\n':
          oss << "\\n";
          break;
        case '\r':
          oss << "\\r";
          break;
        case '\t':
          oss << "\\t";
          break;
        default:
          oss << c;
          break;
      }
    }
    return oss.str();
  }

  static void createDirectory(const std::string& path) {
    if (path.empty()) {
      return;
    }
    std::error_code ec;
    std::filesystem::create_directories(path, ec);
  }

  static std::string absolutePath(const std::string& path) {
    std::error_code ec;
    const auto absolute = std::filesystem::absolute(path, ec);
    return ec ? path : absolute.lexically_normal().string();
  }

  template <typename T>
  void recordNumeric(const std::string& name, MetricKind kind, T value) {
    QueuedSample sample;
    sample.kind = kind;
    sample.name = name;
    sample.receive_time_sec = nowSec();
    sample.numeric_value = static_cast<double>(value);
    enqueue(std::move(sample));
  }

  // Shared implementation behind registerCostMetric/registerScoreMetric.
  // Cost thresholds are upper bounds; score thresholds are lower bounds.
  void registerNumericMetric(const std::string& name, MetricKind kind,
                             double warning_threshold, double error_threshold) {
    std::lock_guard<std::mutex> lock(state_mutex_);
    if (finalized_) {
      return;
    }
    if (isRegisteredLocked(name)) {
      return;
    }
    registered_order_.push_back({name, kind});
    auto& state = numeric_states_[name];
    state.kind = kind;
    state.created_time_sec = created_time_sec_;
    if (kind == MetricKind::Score) {
      state.threshold.warn_if_below = warning_threshold;
      state.threshold.error_if_below = error_threshold;
    } else {
      state.threshold.warn_if_above = warning_threshold;
      state.threshold.error_if_above = error_threshold;
    }
  }

  // The only function called by producer-facing record*() methods after they
  // package a sample. It intentionally does no statistics or file I/O.
  void enqueue(QueuedSample sample) {
    std::lock_guard<std::mutex> lock(queue_mutex_);
    if (pending_samples_.size() >= config_.max_pending_samples) {
      if (config_.drop_when_queue_full) {
        ++dropped_sample_count_;
        return;
      }
    }
    pending_samples_.push_back(std::move(sample));
    queue_cv_.notify_one();
  }

  bool isRegisteredLocked(const std::string& name) const {
    return std::any_of(
        registered_order_.begin(), registered_order_.end(),
        [&](const RegisteredMetric& item) { return item.name == name; });
  }

  // Worker thread main loop: drain queue, update state/results, and perform
  // periodic file output. state_mutex_ is held only for the processing phase.
  void processLoop() {
    try {
      while (running_.load()) {
        std::vector<QueuedSample> batch;
        {
          std::unique_lock<std::mutex> lock(queue_mutex_);
          queue_cv_.wait_for(
              lock, secondsToDuration(config_.process_interval_sec),
              [&] { return !running_.load() || !pending_samples_.empty(); });
          drainPendingSamplesLocked(batch);
        }

        const double now = nowSec();
        {
          std::lock_guard<std::mutex> lock(state_mutex_);
          processBatchLocked(batch);
          trimOldSamplesLocked(now);
          updateMetricResultsLocked(now);
          maybeAppendMetricsCsvRowLocked(now);
          maybeWriteTmpSnapshotFileLocked(now);
        }
      }

      // Shutdown path: after running_ becomes false, drain anything that was
      // queued before stop() woke the worker. The normal loop may exit before
      // the final samples are processed, so this preserves the last data points
      // and writes one final metrics/raw/JSON snapshot.
      std::vector<QueuedSample> batch;
      {
        std::lock_guard<std::mutex> lock(queue_mutex_);
        drainPendingSamplesLocked(batch);
      }
      const double now = nowSec();
      {
        std::lock_guard<std::mutex> lock(state_mutex_);
        processBatchLocked(batch);
        trimOldSamplesLocked(now);
        updateMetricResultsLocked(now);
        appendMetricsCsvRowLocked(now);
        writeTmpSnapshotFileLocked(now);
      }
    } catch (const std::exception& e) {
      std::lock_guard<std::mutex> lock(state_mutex_);
      internal_error_message_ =
          std::string("processLoop exception: ") + e.what();
    } catch (...) {
      std::lock_guard<std::mutex> lock(state_mutex_);
      internal_error_message_ = "processLoop unknown exception";
    }
  }

  // Moves all pending samples into a local batch while queue_mutex_ is held.
  void drainPendingSamplesLocked(std::vector<QueuedSample>& batch) {
    batch.reserve(batch.size() + pending_samples_.size());
    while (!pending_samples_.empty()) {
      batch.push_back(std::move(pending_samples_.front()));
      pending_samples_.pop_front();
    }
  }

  // Applies a drained batch to per-metric states. state_mutex_ must be held.
  void processBatchLocked(const std::vector<QueuedSample>& batch) {
    for (const auto& sample : batch) {
      has_received_any_data_ = true;
      last_any_receive_time_sec_ = sample.receive_time_sec;

      if (sample.kind == MetricKind::Header) {
        processHeaderSampleLocked(sample);
      } else {
        processNumericSampleLocked(sample);
      }
    }
  }

  // Updates sequence loss counters and the latency/frequency window.
  void processHeaderSampleLocked(const QueuedSample& sample) {
    if (!sample.sequence || !sample.source_timestamp_sec) {
      return;
    }

    auto& state = header_states_[sample.name];
    if (state.created_time_sec <= 0.0) {
      state.created_time_sec = sample.receive_time_sec;
    }
    state.has_received_data = true;
    state.last_receive_time_sec = sample.receive_time_sec;
    ++state.total_received_count;

    const std::uint64_t sequence = *sample.sequence;
    if (state.has_last_sequence) {
      if (sequence > state.last_sequence + 1) {
        state.total_lost_count += sequence - state.last_sequence - 1;
      } else if (sequence <= state.last_sequence) {
        ++state.total_out_of_order_count;
      }
    }
    if (!state.has_last_sequence || sequence > state.last_sequence) {
      state.last_sequence = sequence;
      state.has_last_sequence = true;
    }

    HeaderSample raw;
    raw.sequence = sequence;
    raw.source_timestamp_sec = *sample.source_timestamp_sec;
    raw.receive_time_sec = sample.receive_time_sec;
    state.window.push_back(raw);
    state.latest_sample = raw;
    state.has_latest_sample = true;
    appendHeaderRawSampleLocked(sample.name, raw);
  }

  // Ignores non-finite values so NaN/Inf do not poison numeric statistics.
  void processNumericSampleLocked(const QueuedSample& sample) {
    if (!sample.numeric_value || !isFinite(*sample.numeric_value)) {
      return;
    }

    auto& state = numeric_states_[sample.name];
    if (state.created_time_sec <= 0.0) {
      state.created_time_sec = sample.receive_time_sec;
    }
    state.kind = sample.kind;
    state.has_received_data = true;
    state.last_receive_time_sec = sample.receive_time_sec;
    ++state.total_count;

    NumericSample raw;
    raw.value = *sample.numeric_value;
    raw.receive_time_sec = sample.receive_time_sec;
    state.window.push_back(raw);
    state.latest_sample = raw;
    state.has_latest_sample = true;
    appendNumericRawSampleLocked(sample.name, raw);
  }

  // Keeps the sliding windows bounded by time and count.
  void trimOldSamplesLocked(double now) {
    const double cutoff = now - config_.statistics_window_sec;
    for (auto& item : header_states_) {
      auto& window = item.second.window;
      while (!window.empty() && window.front().receive_time_sec < cutoff) {
        window.pop_front();
      }
      while (window.size() > config_.max_samples_per_metric) {
        window.pop_front();
      }
    }
    for (auto& item : numeric_states_) {
      auto& window = item.second.window;
      while (!window.empty() && window.front().receive_time_sec < cutoff) {
        window.pop_front();
      }
      while (window.size() > config_.max_samples_per_metric) {
        window.pop_front();
      }
    }
  }

  // Rebuilds latest_results_ from current state. latest_results_cache_ is the
  // worker-owned copy used by CSV/JSON writers.
  void updateMetricResultsLocked(double now) {
    std::vector<MetricResult> results;
    results.push_back(makeModuleResultLocked(now));

    for (const auto& item : header_states_) {
      results.push_back(makeHeaderResult(item.first, item.second, now));
    }
    for (const auto& item : numeric_states_) {
      results.push_back(makeNumericResult(item.first, item.second, now));
    }

    {
      std::lock_guard<std::mutex> lock(results_mutex_);
      latest_results_ = results;
    }
    latest_results_cache_ = std::move(results);
  }

  // Availability is computed before threshold semantics; missing/stopped data
  // should dominate any value-based interpretation.
  Status availabilityStatus(bool has_data, double created_time_sec,
                            double last_receive_time_sec, double now) const {
    if (!has_data && now - created_time_sec >= config_.no_data_timeout_sec) {
      return Status::NoData;
    }
    if (has_data &&
        now - last_receive_time_sec >= config_.data_lost_timeout_sec) {
      return Status::DataLost;
    }
    return Status::Ok;
  }

  Status applyThresholdStatus(Status current, double value,
                              const MetricThreshold& threshold) const {
    if (current == Status::NoData || current == Status::DataLost ||
        !isFinite(value)) {
      return current;
    }
    if (threshold.error_if_above && value >= *threshold.error_if_above) {
      return Status::Error;
    }
    if (threshold.error_if_below && value <= *threshold.error_if_below) {
      return Status::Error;
    }
    if (current == Status::Warn) {
      return current;
    }
    if (threshold.warn_if_above && value >= *threshold.warn_if_above) {
      return Status::Warn;
    }
    if (threshold.warn_if_below && value <= *threshold.warn_if_below) {
      return Status::Warn;
    }
    return current;
  }

  // Synthetic result for object-level NoData/DataLost and queue drops.
  MetricResult makeModuleResultLocked(double now) const {
    MetricResult result;
    result.name = config_.module_name;
    result.kind = MetricKind::Module;
    result.update_time_sec = now;
    result.status =
        availabilityStatus(has_received_any_data_, created_time_sec_,
                           last_any_receive_time_sec_, now);
    result.values["monitor_created_time_sec"] = created_time_sec_;
    result.values["last_any_receive_time_sec"] =
        has_received_any_data_ ? last_any_receive_time_sec_
                               : config_.missing_value;
    result.values["time_since_create_sec"] = now - created_time_sec_;
    result.values["time_since_last_any_receive_sec"] =
        has_received_any_data_ ? now - last_any_receive_time_sec_
                               : config_.missing_value;
    result.values["dropped_sample_count"] =
        static_cast<double>(dropped_sample_count_.load());
    result.message = toString(result.status);
    return result;
  }

  // Builds the public result for one sequence/timestamp stream.
  MetricResult makeHeaderResult(const std::string& name,
                                const HeaderMetricState& state,
                                double now) const {
    MetricResult result;
    result.name = name;
    result.kind = MetricKind::Header;
    result.update_time_sec = now;
    result.status =
        availabilityStatus(state.has_received_data, state.created_time_sec,
                           state.last_receive_time_sec, now);
    result.message = toString(result.status);

    result.values["total_received_count"] =
        static_cast<double>(state.total_received_count);
    result.values["total_lost_count"] =
        static_cast<double>(state.total_lost_count);
    result.values["total_out_of_order_count"] =
        static_cast<double>(state.total_out_of_order_count);
    const double denom = static_cast<double>(state.total_lost_count +
                                             state.total_received_count);
    result.values["loss_rate"] =
        denom > 0.0 ? static_cast<double>(state.total_lost_count) / denom : 0.0;
    result.values["last_sequence"] =
        state.has_last_sequence ? static_cast<double>(state.last_sequence)
                                : config_.missing_value;
    addAvailabilityValues(result, state.created_time_sec,
                          state.last_receive_time_sec, state.has_received_data,
                          now);

    if (state.window.empty()) {
      result.values["latency_sec_min"] = config_.missing_value;
      result.values["latency_sec_max"] = config_.missing_value;
      result.values["latency_sec_avg"] = config_.missing_value;
      result.values["frequency_hz"] = 0.0;
      return result;
    }

    double min_latency = std::numeric_limits<double>::infinity();
    double max_latency = -std::numeric_limits<double>::infinity();
    double sum_latency = 0.0;
    for (const auto& sample : state.window) {
      const double latency =
          sample.receive_time_sec - sample.source_timestamp_sec;
      min_latency = std::min(min_latency, latency);
      max_latency = std::max(max_latency, latency);
      sum_latency += latency;
    }
    result.values["latency_sec_min"] = min_latency;
    result.values["latency_sec_max"] = max_latency;
    result.values["latency_sec_avg"] =
        sum_latency / static_cast<double>(state.window.size());
    result.values["frequency_hz"] = headerFrequency(state.window);
    result.status =
        applyThresholdStatus(result.status, result.values["latency_sec_max"],
                             state.latency_threshold);
    result.status =
        applyThresholdStatus(result.status, result.values["frequency_hz"],
                             state.frequency_threshold);
    result.message = toString(result.status);
    return result;
  }

  // Builds the public result for one numeric stream.
  MetricResult makeNumericResult(const std::string& name,
                                 const NumericMetricState& state,
                                 double now) const {
    MetricResult result;
    result.name = name;
    result.kind = state.kind;
    result.update_time_sec = now;
    result.status =
        availabilityStatus(state.has_received_data, state.created_time_sec,
                           state.last_receive_time_sec, now);
    result.message = toString(result.status);
    result.values["total_count"] = static_cast<double>(state.total_count);
    addAvailabilityValues(result, state.created_time_sec,
                          state.last_receive_time_sec, state.has_received_data,
                          now);

    if (state.window.empty()) {
      result.values["count"] = 0.0;
      result.values["min"] = config_.missing_value;
      result.values["max"] = config_.missing_value;
      result.values["avg"] = config_.missing_value;
      if (state.kind == MetricKind::Normal) {
        result.values["variance"] = config_.missing_value;
        result.values["stddev"] = config_.missing_value;
      } else {
        result.values["worst_1_percent_avg"] = config_.missing_value;
      }
      return result;
    }

    std::vector<double> values;
    values.reserve(state.window.size());
    for (const auto& sample : state.window) {
      values.push_back(sample.value);
    }

    const auto minmax = std::minmax_element(values.begin(), values.end());
    const double sum = std::accumulate(values.begin(), values.end(), 0.0);
    const double avg = sum / static_cast<double>(values.size());

    result.values["count"] = static_cast<double>(values.size());
    result.values["min"] = *minmax.first;
    result.values["max"] = *minmax.second;
    result.values["avg"] = avg;

    if (state.kind == MetricKind::Normal) {
      double variance_sum = 0.0;
      for (double value : values) {
        const double delta = value - avg;
        variance_sum += delta * delta;
      }
      const double variance = variance_sum / static_cast<double>(values.size());
      result.values["variance"] = variance;
      result.values["stddev"] = std::sqrt(variance);
    } else {
      result.values["worst_1_percent_avg"] =
          worstOnePercentAverage(values, state.kind == MetricKind::Cost);
      const double threshold_value = state.kind == MetricKind::Cost
                                         ? result.values["max"]
                                         : result.values["min"];
      result.status =
          applyThresholdStatus(result.status, threshold_value, state.threshold);
      result.message = toString(result.status);
    }

    return result;
  }

  // Adds common per-metric availability values to every non-module result.
  void addAvailabilityValues(MetricResult& result, double created_time_sec,
                             double last_receive_time_sec,
                             bool has_received_data, double now) const {
    result.values["created_time_sec"] = created_time_sec;
    result.values["last_receive_time_sec"] =
        has_received_data ? last_receive_time_sec : config_.missing_value;
    result.values["time_since_create_sec"] = now - created_time_sec;
    result.values["time_since_last_receive_sec"] =
        has_received_data ? now - last_receive_time_sec : config_.missing_value;
  }

  // Frequency is based on receive timestamps inside the current statistics
  // window, not on sequence numbers.
  static double headerFrequency(const std::deque<HeaderSample>& window) {
    if (window.size() < 2) {
      return 0.0;
    }
    const double duration =
        window.back().receive_time_sec - window.front().receive_time_sec;
    if (duration <= 0.0) {
      return 0.0;
    }
    return static_cast<double>(window.size() - 1) / duration;
  }

  // For cost high values are bad; for score low values are bad.
  static double worstOnePercentAverage(std::vector<double> values,
                                       bool high_is_bad) {
    if (values.empty()) {
      return std::numeric_limits<double>::quiet_NaN();
    }
    const std::size_t count = std::max<std::size_t>(
        1, static_cast<std::size_t>(std::ceil(values.size() * 0.01)));
    if (high_is_bad) {
      std::sort(values.begin(), values.end(), std::greater<double>());
    } else {
      std::sort(values.begin(), values.end());
    }
    const double sum =
        std::accumulate(values.begin(), values.begin() + count, 0.0);
    return sum / static_cast<double>(count);
  }

  // Constructs the fixed all-metrics CSV schema from registered metrics.
  void buildMetricsColumnsLocked() {
    metrics_columns_.clear();
    addStatusColumns(config_.module_name, MetricKind::Module);
    addColumn(config_.module_name, MetricKind::Module, "time_since_create_sec");
    addColumn(config_.module_name, MetricKind::Module,
              "time_since_last_any_receive_sec");
    addColumn(config_.module_name, MetricKind::Module, "dropped_sample_count");

    for (const auto& registered : registered_order_) {
      if (registered.kind == MetricKind::Header) {
        addHeaderColumns(registered.name);
      } else {
        addNumericColumns(registered.name, registered.kind);
      }
    }
  }

