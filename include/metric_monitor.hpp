#pragma once

/*
MetricMonitor
=============

Single-file, header-only C++17 metric and health monitor for UAV/robotics
algorithm modules. It is intentionally independent from ROS message types and
external libraries so it can be dropped into ROS1, ROS2, simulation, or plain
C++ tools.

Features
--------
  - Records four source kinds:
      Header: sequence + timestamp streams such as odometry, sensor frames, or
              planner commands. Calculates loss, latency, frequency, and
              out-of-order count.
      Cost:   numeric streams where smaller is better, such as solve time,
              optimizer cost, or program time cost.
      Score:  numeric streams where larger is better, such as quality score or
              confidence.
      Normal: numeric streams where magnitude has no good/bad direction, such
              as queue size, temperature, or map point count.
  - Uses double UTC seconds since Unix epoch for every timestamp.
  - Uses double seconds for every duration and interval.
  - Producer calls record*() only enqueue data and return quickly.
  - A background thread processes samples asynchronously.
  - Sliding-window statistics:
      Header: total_received_count, total_lost_count, loss_rate,
              total_out_of_order_count, latency min/max/avg, frequency_hz,
              last_sequence.
      Cost:   count, min, max, avg, worst_1_percent_avg where high values are
              worst.
      Score:  count, min, max, avg, worst_1_percent_avg where low values are
              worst.
      Normal: count, min, max, avg, variance, stddev.
  - Availability events:
      NoData:   object or registered metric exists, but no sample arrived after
                no_data_timeout_sec.
      DataLost: at least one sample arrived, but no new sample arrived after
                data_lost_timeout_sec.
  - One fixed-schema metrics CSV containing all calculated metrics and event
    states. A new row is appended when a diagnostics snapshot is generated.
  - One raw CSV file per registered data source, with one row per raw sample.
  - Atomic-style JSON snapshot overwrite under /tmp or another configured
    snapshot directory.
  - Queue overflow policy can drop diagnostic samples instead of blocking flight
    or algorithm callbacks.

Scope And Constraints
---------------------
  - This is a lightweight in-process utility, not a replacement for a full
    observability stack.
  - The core class has no dependency on ROS message types.
  - Producer-facing record*() calls should not calculate statistics, sort data,
    format strings, or write files.
  - Exact real-time guarantees are not claimed, but the producer path is kept
    bounded and predictable for common callback usage.
  - The implementation is header-only and uses only the C++ standard library.

Core Concepts
-------------
  - Metric name:
      Each source is identified by a stable string name, for example "odom",
      "planner_cmd", "mpc_solve_time_ms", "optimizer_final_cost", or
      "trajectory_score". Names should be unique inside one MetricMonitor.
  - MetricKind:
      Module: module-level availability result generated by the monitor itself.
      Header: sequence/timestamp stream.
      Cost:   numeric stream where smaller values are better.
      Score:  numeric stream where larger values are better.
      Normal: numeric stream where value magnitude is neutral.
  - Numeric type handling:
      recordCost(), recordScore(), and recordNormal() accept common arithmetic
      types. Values are converted to double internally to keep storage,
      statistics, CSV, and JSON output simple.
  - Time representation:
      All timestamps are double UTC seconds since Unix epoch. All durations and
      configuration intervals are double seconds.
  - Clock injection:
      MetricMonitorConfig::clock_now_sec may be set by tests or simulations.
      If unset, MetricMonitor uses std::chrono::system_clock converted to
      double UTC epoch seconds.

Design Insights
---------------
  - Register metrics during init when you need fixed CSV columns, raw CSV files,
    or NoData detection before the first sample.
  - finalizeSchema() freezes the CSV schema. After this point, late unregistered
    metrics may still be processed internally, but they will not be added to the
    fixed metrics CSV header or get raw CSV files.
  - start() calls finalizeSchema() automatically if needed.
  - The metrics CSV is a PlotJuggler-friendly wide table:
        time,<metric>/<stat>,<metric>/status/data_lost,...
    It writes the latest known value for every registered signal on each row.
    If a value does not exist yet, missing_value is written.
  - Raw CSV files append every raw sample processed by the background thread.
  - All file I/O and statistics calculations happen on the background thread.
  - latestResults() returns a copy and is safe for callers to inspect.

Statistics
----------
  - Header metrics:
      Input values are sequence, source_timestamp_sec, and receive_time_sec.
      Calculated values are total_received_count, total_lost_count, loss_rate,
      total_out_of_order_count, latency_sec_min, latency_sec_max,
      latency_sec_avg, frequency_hz, and last_sequence.

      Loss calculation:
        if current_sequence > last_sequence + 1:
          total_lost_count += current_sequence - last_sequence - 1
        else if current_sequence <= last_sequence:
          total_out_of_order_count += 1

      Loss rate:
        loss_rate = total_lost_count /
                    (total_lost_count + total_received_count)

      Latency:
        latency_sec = receive_time_sec - source_timestamp_sec

      Both timestamps must share the same UTC epoch representation. If a source
      timestamp uses another clock, convert it before calling recordHeader().

  - Cost metrics:
      Smaller is better. Calculated values are total_count, count, min, max,
      avg, and worst_1_percent_avg. The worst 1 percent are the largest values.

  - Score metrics:
      Larger is better. Calculated values are total_count, count, min, max,
      avg, and worst_1_percent_avg. The worst 1 percent are the smallest values.

  - Normal metrics:
      Direction is neutral. Calculated values are total_count, count, min, max,
      avg, variance, and stddev.

  - 1 percent worst average:
      worst_count = max(1, ceil(N * 0.01))
      Cost metrics average the largest worst_count values.
      Score metrics average the smallest worst_count values.

  - Windowing:
      Statistics are calculated over samples newer than
      now_sec - statistics_window_sec. The monitor also enforces
      max_samples_per_metric to prevent unbounded memory growth.

Status Values
-------------
  - Ok:
      Metric has fresh data and no warning/error threshold violation.
  - Warn:
      Warning threshold violation.
  - Error:
      Error threshold violation. Availability statuses take priority over value
      thresholds.
  - NoData:
      The monitor object or a registered metric exists, but no sample has ever
      been received after no_data_timeout_sec.
  - DataLost:
      At least one sample was received before, but no new sample arrived for
      data_lost_timeout_sec.

  Object-level availability:
    if !has_received_any_data and
       now_sec - monitor_created_time_sec >= no_data_timeout_sec:
      emit module-level NoData
    else if has_received_any_data and
            now_sec - last_any_receive_time_sec >= data_lost_timeout_sec:
      emit module-level DataLost

  Per-metric availability:
    if !has_received_data and now_sec - created_time_sec >= no_data_timeout_sec:
      status = NoData
    else if has_received_data and
            now_sec - last_receive_time_sec >= data_lost_timeout_sec:
      status = DataLost

API Usage
---------
  1. Create a MetricMonitorConfig.
  2. Register all metrics needed in CSV logs and startup NoData detection.
     Header/cost/score registration requires warning and error thresholds.
     Header thresholds are max-latency upper bounds and min-frequency lower
     bounds. Cost thresholds are max value upper bounds. Score thresholds are
     min value lower bounds.
  3. Optionally call finalizeSchema(); start() will call it if you do not.
  4. Call start().
  5. Call recordHeader(), recordCost(), recordScore(), and recordNormal() from
     callbacks or algorithm loops.
  6. Call latestResults() when you need the current calculated state.
  7. Call stop() during shutdown. The destructor also calls stop().

Example
-------
#include <chrono>
#include <iostream>
#include <thread>

#include "metric_monitor.hpp"

int main() {
  using metric_monitor::MetricMonitor;
  using metric_monitor::MetricMonitorConfig;
  using metric_monitor::Status;

  MetricMonitorConfig config;
  config.module_name = "planner_example";
  config.log_directory = "./metric_monitor_logs";
  config.snapshot_directory = "/tmp";
  config.process_interval_sec = 0.02;
  config.metrics_csv_write_interval_sec = 0.5;
  config.tmp_snapshot_write_interval_sec = 0.5;
  config.statistics_window_sec = 5.0;
  config.no_data_timeout_sec = 5.0;
  config.data_lost_timeout_sec = 0.2;

  MetricMonitor monitor(config);
  monitor.registerHeaderMetric(
      "odom",
      0.03,  // warn when max latency is at or above this many seconds
      0.08,  // error when max latency is at or above this many seconds
      40.0,  // warn when frequency is at or below this many Hz
      20.0   // error when frequency is at or below this many Hz
  );
  monitor.registerCostMetric("mpc_solve_time_ms", 4.0, 8.0);
  monitor.registerScoreMetric("trajectory_score", 80.0, 60.0);
  monitor.registerNormalMetric("local_map_points");
  monitor.finalizeSchema();
  monitor.start();

  auto nowSec = [] {
    using Clock = std::chrono::system_clock;
    return std::chrono::duration<double>(Clock::now().time_since_epoch())
        .count();
  };

  {
    // test no data error
    std::this_thread::sleep_for(std::chrono::milliseconds(10000));

    std::cout << "\n\n" << std::endl;
    std::cout << "----------------Test result for no data event----------------"
              << std::endl;
    const auto results = monitor.latestResults();
    for (const auto& result : results) {
      std::cout << result.name
                << " status: " << MetricMonitor::toString(result.status)
                << '\n';
      for (const auto& value : result.values) {
        std::cout << "  " << value.first << ": " << value.second << '\n';
      }
    }
    std::cout << "-------------------------------------------------------------"
              << std::endl;
  }

  for (std::uint64_t i = 0; i < 800; ++i) {
    const double receive_time = nowSec();
    const double source_time = receive_time - 0.01;
    const std::uint64_t sequence =
        i < 40 ? i : i + 1;  // Simulate one lost odom frame.

    monitor.recordHeader("odom", sequence, source_time);
    monitor.recordCost("mpc_solve_time_ms",
                       2.0 + static_cast<double>(i % 7) * 0.25);
    monitor.recordScore("trajectory_score", 100.0 - static_cast<double>(i % 5));
    monitor.recordNormal("local_map_points", 5000 + static_cast<int>(i % 20));

    std::this_thread::sleep_for(std::chrono::milliseconds(20));

    if (i == 100) {
      std::cout << "\n\n" << std::endl;
      std::cout
          << "---------------- Test result for normal event----------------"
          << std::endl;
      const auto results = monitor.latestResults();
      for (const auto& result : results) {
        std::cout << result.name
                  << " status: " << MetricMonitor::toString(result.status)
                  << '\n';
        for (const auto& value : result.values) {
          std::cout << "  " << value.first << ": " << value.second << '\n';
        }
      }
      std::cout
          << "-------------------------------------------------------------"
          << std::endl;
    }
  }

  // test data lost error
  std::this_thread::sleep_for(std::chrono::milliseconds(600));
  std::cout << "\n\n" << std::endl;
  std::cout << "---------------Test result for data lost event---------------"
            << std::endl;
  const auto results = monitor.latestResults();
  for (const auto& result : results) {
    std::cout << result.name
              << " status: " << MetricMonitor::toString(result.status) << '\n';
    for (const auto& value : result.values) {
      std::cout << "  " << value.first << ": " << value.second << '\n';
    }
  }
  std::cout << "-------------------------------------------------------------"
            << std::endl;

  monitor.stop();

  std::cout << "CSV logs written under ./metric_monitor_logs\n";
  std::cout << "JSON snapshot written to "
               "/tmp/planner_example_metrics_snapshot.json\n";
  return 0;
}



ROS Timestamp Adapter
---------------------
  Keep ROS-specific types outside the core class. Convert ROS timestamps to
  double UTC seconds before calling recordHeader().

  inline double rosStampToSec(int64_t sec, uint32_t nsec) {
    return static_cast<double>(sec) + static_cast<double>(nsec) * 1e-9;
  }

Output Files
------------
  Metrics CSV:
    <log_directory>/<module_name>_<YYYYMMDD_HHMMSS>_metrics.csv

    The first line is fixed after finalizeSchema(). Rows are appended at
    metrics_csv_write_interval_sec.

    Layout:
      time,<signal_1>,<signal_2>,...

    Rules:
      - The first column is always time, using double UTC epoch seconds.
      - Every other column is numeric.
      - Signal names are path-like, for example odom/loss_rate or
        mpc_solve_time_ms/avg.
      - New columns are not added after data rows have started.
      - Each row contains the latest known value for every registered signal.
      - Missing values are written as missing_value.
      - String messages are not written to CSV.
      - Status values are encoded as 0/1 status columns:
          <metric>/status/ok
          <metric>/status/warn
          <metric>/status/error
          <metric>/status/no_data
          <metric>/status/data_lost

  Raw source CSV:
    <log_directory>/<module_name>_<YYYYMMDD_HHMMSS>_<source_name>_raw.csv

    One file is created for each registered data source. One row is appended
    for every raw sample processed by the background thread.

    Header stream layout:
      time,source_timestamp_sec,receive_time_sec,sequence,latency_sec

    Numeric stream layout:
      time,receive_time_sec,value

  JSON snapshot:
    <snapshot_directory>/<module_name>_metrics_snapshot.json

    The file is overwritten through a temporary file + rename pattern at
    tmp_snapshot_write_interval_sec. Missing/non-finite numeric values are
    written as null so strict JSON loaders can parse the file.

    Shape:
      {
        "module": "...",
        "wall_time_sec": 1781600000.0,
        "results": [
          {
            "name": "...",
            "kind": "cost",
            "status": "ok",
            "message": "...",
            "values": { "avg": 3.4 }
          }
        ]
      }

Operational Notes
-----------------
  - Use UTC/system time consistently for both source_timestamp_sec and internal
    receive time if you care about latency.
  - For source timestamps that are not comparable to UTC epoch time, latency is
    not meaningful without an adapter.
  - The default missing_value is NaN, which PlotJuggler and many analysis tools
    can treat as missing data.
  - drop_when_queue_full=true is recommended for flight/control paths because
    diagnostics should not block core algorithms.
  - Duplicate metric registrations are ignored.
  - MetricThreshold stores warning/error thresholds configured at registration.
    Header uses latency_sec_max as an upper bound and frequency_hz as a lower
    bound. Cost uses max as an upper bound, and score uses min as a lower
    bound. Availability statuses still take priority.

Testing Guidance
----------------
  Useful unit tests:
    - Cost metric min, max, average, and largest 1 percent average.
    - Score metric smallest 1 percent average.
    - Normal metric variance and standard deviation.
    - Header sequence loss and out-of-order detection.
    - Registered metric NoData timeout.
    - Previously active metric DataLost timeout.
    - Sliding-window trimming.
    - Queue overflow behavior.
    - Valid JSON snapshot output.
    - Metrics CSV appends one full snapshot row.
    - Raw CSV appends one row for every valid raw sample.
    - start() and stop() idempotency.

  Useful runtime checks:
    - Record from a high-frequency loop and confirm callback latency remains
      stable.
    - Load metrics/raw CSV files in PlotJuggler.
    - Run with an unwritable log directory and confirm the algorithm continues.
    - Kill and restart a dashboard reading the /tmp snapshot.

Extensibility
-------------
  Future metric kinds can be added by extending:
    - MetricKind
    - QueuedSample payload
    - A kind-specific state struct
    - A kind-specific statistics function
    - CSV/JSON serialization of the new kind

  Keep public record*() methods small wrappers around enqueue(). This preserves
  the low-overhead producer path while allowing the background thread to own all
  new aggregation and file-output behavior.

  Useful future extensions:
    - Histogram metrics.
    - Event counters.
    - Boolean state metrics.
    - String/status metrics in JSON snapshots.
    - More per-metric MetricThreshold options beyond the current registration
      thresholds.
    - Lock-free MPSC queue if profiling shows the mutex queue is too expensive.
    - Optional JSON-lines or key/value debug logs beside the PlotJuggler CSVs.
    - Count-window statistics in addition to the current time-window statistics.
    - Welford variance and nth_element worst-percent calculations for very
      large windows.
    - YAML, ROS parameter, or direct C++ API threshold configuration.

Error Handling
--------------
  - File open/write failures should not throw through the processing thread.
    This implementation stores an internal error message and continues running.
  - Invalid numeric values such as NaN and Inf are ignored for numeric streams.
  - start() and stop() are idempotent.
  - The destructor calls stop().
  - If the pending queue is full and drop_when_queue_full is true, the new
    diagnostic sample is dropped and dropped_sample_count is incremented.
  - If drop_when_queue_full is false, the queue may grow beyond
    max_pending_samples; use this mode only when diagnostics must be retained
    and callback latency is less important.

Compile Example
---------------
  g++ -std=c++17 -O2 -Wall -Wextra -pedantic example.cpp -pthread -o
metric_monitor_example
*/

